// Splits the two big generated data files so a page only downloads what it shows.
//   total_war/data/skill_trees.js      (16 MB, 366 skill sets)  -> total_war/data/skill_trees/<skill_set>.js   (about 45 KB each)
//   total_war/data/character_details.js (4.2 MB, 1650 entries)  -> total_war/data/details/<template_key>.js    (about 3 KB each)
//                                                                  total_war/data/portrait_urls.js            (key -> portrait path, ~110 KB)
// The monoliths stay in the repo (they are generator output); the split files are git-ignored and rebuilt by
// `npm run build:data` and by the deploy workflow. dist/ leaves the monoliths out (scripts/build_site.mjs).
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import vm from 'node:vm';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const data = join(root, 'total_war', 'data');
// keys with accents (e.g. lü_you) become safe file names: ü -> ~fc. Same rule as window.dataFileKey in scripts/portraits.js.
const fileKey = (k) => k.replace(/[^A-Za-z0-9_]/g, (ch) => '~' + ch.codePointAt(0).toString(16));

function load(file, name) {
  const src = readFileSync(join(data, file), 'utf8').replace(new RegExp(`\\bconst ${name}\\b`), `var ${name}`);
  const ctx = {};
  vm.createContext(ctx);
  vm.runInContext(src, ctx);
  return ctx[name];
}

function writeEach(dirName, entries, wrap) {
  const dir = join(data, dirName);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  let bytes = 0;
  for (const [key, value] of Object.entries(entries)) {
    const text = wrap(key, JSON.stringify(value));
    writeFileSync(join(dir, `${fileKey(key)}.js`), text);
    bytes += text.length;
  }
  return { count: Object.keys(entries).length, bytes };
}

// skill trees
const trees = load('skill_trees.js', 'SKILL_TREE_DATA');
const st = writeEach('skill_trees', trees, (k, json) => `(window.SKILL_TREE_DATA = window.SKILL_TREE_DATA || {})[${JSON.stringify(k)}] = ${json};\n`);

// character details + a small portrait map
const details = load('character_details.js', 'CHARACTER_DETAILS');
const cd = writeEach('details', details, (k, json) =>
  `window.CHARACTER_DETAILS = window.CHARACTER_DETAILS || {};\nwindow.CHARACTER_DETAILS_LOOKUP = window.CHARACTER_DETAILS;\nCHARACTER_DETAILS[${JSON.stringify(k)}] = ${json};\n`);
const portraits = {};
for (const [k, v] of Object.entries(details)) if (v?.portrait?.url) portraits[k] = v.portrait.url;
writeFileSync(join(data, 'portrait_urls.js'), `// Generated by scripts/split_data.mjs from character_details.js. Do not edit.\nwindow.PORTRAIT_URLS = ${JSON.stringify(portraits)};\n`);

const mb = (n) => (n / 1e6).toFixed(1);
console.log(`skill trees: ${st.count} files, ${mb(st.bytes)} MB total; details: ${cd.count} files, ${mb(cd.bytes)} MB total; portrait map: ${Object.keys(portraits).length} entries`);
