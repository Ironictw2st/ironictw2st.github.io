// Builds, from db/roadmap_seed.json (or a D1 export, see below):
//   total_war/data/roadmap.json  - the static fallback the public page and /api/roadmap use when D1 is unreachable
//   db/seed_roadmap.sql          - loads the same rows into a local or remote D1 (only if the table is empty)
//
// Usage:  node scripts/build_roadmap_json.mjs [--from-file path.json]
// Deploy keeps the fallback fresh: the GitHub Action runs `wrangler d1 execute ... --json` and passes it with --from-file.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const argFile = process.argv.indexOf('--from-file');
const srcPath = argFile > -1 ? process.argv[argFile + 1] : join(root, 'db', 'roadmap_seed.json');
const src = JSON.parse(readFileSync(srcPath, 'utf8'));
// accepts the seed file ({items}), a plain array, or `wrangler d1 execute --json` output ([{results}])
const items = src.items ?? (Array.isArray(src) && src[0]?.results ? src[0].results : src);

if (!Array.isArray(items) || items.length === 0) { console.error('no roadmap items found in input'); process.exit(1); }
const ORDER = { live: 0, next: 1, planned: 2, idea: 3 };
const now = new Date().toISOString();
const counter = {};
const rows = items.map((it, i) => {
  counter[it.status] = (counter[it.status] ?? 0) + 10;
  return {
    id: it.id ?? i + 1, title: it.title, description: it.description ?? '', status: it.status, category: it.category,
    sort_order: it.sort_order ?? counter[it.status], version: it.version ?? '', release_date: it.release_date ?? '',
    draft: it.draft ? 1 : 0, updated_at: it.updated_at ?? now,
  };
}).sort((a, b) => ORDER[a.status] - ORDER[b.status] || a.sort_order - b.sort_order);

writeFileSync(join(root, 'total_war', 'data', 'roadmap.json'),
  JSON.stringify({ source: 'static', updated_at: now, items: rows }, null, 2) + '\n');

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const sql = [
  '-- Generated by scripts/build_roadmap_json.mjs. Seeds the roadmap once (skipped when a seed history row exists).',
  ...rows.map((r) =>
    `INSERT INTO roadmap_items (id, title, description, status, category, sort_order, version, release_date, draft, updated_at)\n` +
    `SELECT ${r.id}, ${q(r.title)}, ${q(r.description)}, ${q(r.status)}, ${q(r.category)}, ${r.sort_order}, ${q(r.version)}, ${q(r.release_date)}, ${r.draft}, ${q(r.updated_at)}\n` +
    `WHERE NOT EXISTS (SELECT 1 FROM roadmap_history WHERE action = 'seed');`),
  `INSERT INTO roadmap_history (saved_at, saved_by, action, summary, snapshot)\n` +
  `SELECT ${q(now)}, 'seed', 'seed', 'Initial draft roadmap', COALESCE(json_group_array(json_object('id', id, 'title', title, 'description', description, 'status', status, 'category', category, 'sort_order', sort_order, 'version', version, 'release_date', release_date, 'draft', draft, 'updated_at', updated_at)), '[]') FROM (SELECT * FROM roadmap_items ORDER BY id)\n` +
  `WHERE NOT EXISTS (SELECT 1 FROM roadmap_history);`,
  '',
].join('\n');
writeFileSync(join(root, 'db', 'seed_roadmap.sql'), sql);
console.log(`roadmap: ${rows.length} items -> total_war/data/roadmap.json + db/seed_roadmap.sql`);
